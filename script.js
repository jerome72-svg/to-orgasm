
/*
  TO ORGASM — PURCHASE & CREATOR REFERRAL ROUTING

  HOW IT WORKS:

  1. A creator shares:
     https://YOUR-WEBSITE/?ref=creatorname

  2. This script remembers the referral code.

  3. When the visitor clicks Buy, they are sent
     through that creator's actual Gumroad affiliate link.

  4. Gumroad handles purchase attribution and commission.

  IMPORTANT:
  Replace the example links below with the real affiliate
  links generated by Gumroad.
*/

const CONFIG = {

  // Replace with your actual Gumroad product URL.
  PRODUCT_URL: "https://gumroad.com/l/YOUR-PRODUCT-SLUG",

  // Add each creator's referral code and Gumroad affiliate link here.
  AFFILIATES: {

    "creatorname": "PASTE_CREATOR_A_GUMROAD_AFFILIATE_LINK_HERE",

    "creator2": "PASTE_CREATOR_B_GUMROAD_AFFILIATE_LINK_HERE",

    "creator3": "PASTE_CREATOR_C_GUMROAD_AFFILIATE_LINK_HERE"

  },

  REFERRAL_STORAGE_KEY: "to_orgasm_referral",

  // Keep the referral for 30 days.
  REFERRAL_DURATION: 30 * 24 * 60 * 60 * 1000

};

/* SAVE REFERRAL WHEN A VISITOR ARRIVES */

function captureReferral() {

  const params = new URLSearchParams(window.location.search);
  const referralCode = params.get("ref");

  if (!referralCode) return;

  const normalizedCode = referralCode.trim().toLowerCase();

  // Only save recognised creator codes.
  if (!Object.prototype.hasOwnProperty.call(
    CONFIG.AFFILIATES,
    normalizedCode
  )) {
    return;
  }

  const referralData = {
    code: normalizedCode,
    savedAt: Date.now()
  };

  try {
    localStorage.setItem(
      CONFIG.REFERRAL_STORAGE_KEY,
      JSON.stringify(referralData)
    );
  } catch (error) {
    console.warn("Referral could not be saved.", error);
  }

}

/* GET THE CURRENT REFERRAL */

function getActiveReferral() {

  try {

    const stored = localStorage.getItem(
      CONFIG.REFERRAL_STORAGE_KEY
    );

    if (!stored) return null;

    const referralData = JSON.parse(stored);

    const isExpired =
      Date.now() - referralData.savedAt >
      CONFIG.REFERRAL_DURATION;

    if (isExpired) {
      localStorage.removeItem(CONFIG.REFERRAL_STORAGE_KEY);
      return null;
    }

    if (!CONFIG.AFFILIATES[referralData.code]) {
      return null;
    }

    return referralData.code;

  } catch (error) {
    console.warn("Could not read referral information.", error);
    return null;
  }

}

/* SELECT THE CORRECT GUMROAD DESTINATION */

function getPurchaseUrl() {

  const referralCode = getActiveReferral();

  if (
    referralCode &&
    CONFIG.AFFILIATES[referralCode] &&
    CONFIG.AFFILIATES[referralCode].startsWith("https://")
  ) {
    return CONFIG.AFFILIATES[referralCode];
  }

  return CONFIG.PRODUCT_URL;

}

/* CONNECT ALL PURCHASE BUTTONS */

function setupPurchaseButtons() {

  const buttons = document.querySelectorAll(
    "#buy-button, [data-buy]"
  );

  buttons.forEach(button => {

    button.href = getPurchaseUrl();

    button.addEventListener("click", function(event) {

      const destination = getPurchaseUrl();

      // Prevent accidental navigation to an unfinished placeholder.
      if (
        !destination ||
        destination.includes("YOUR-PRODUCT-SLUG") ||
        destination.includes("PASTE_CREATOR")
      ) {
        event.preventDefault();

        alert(
          "Checkout is being prepared. Please check back soon."
        );
      }

    });

  });

}

/* INITIALIZE */

captureReferral();
setupPurchaseButtons();